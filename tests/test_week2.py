"""
tests/test_week2.py -- Week 2 tests (Study A)

Builds SYNTHETIC workbooks shaped like the SAFE BPM6 time-series file and a Wind export,
and checks collect_bop.py and register_wind.py on them. Every number is a placeholder
generated by this test (a simple formula of the row/column position); none is real data.
No network access is used: collect_bop.py runs with --file.

Run from the project root:   python -m unittest tests.test_week2 -v
"""
